"""
Least-Privilege Policy Generator for SentinelGate.
Generates minimal-privilege configurations for Harbor, Finch, and Open Policy Agent (OPA).
"""

from typing import Dict, Any, List, Optional
import uuid
from datetime import datetime, timezone
from sentinel.models import RemediationPlan, SystemType, RiskLevel
from sentinel.config import SCOPE_RISK_WEIGHTS
from sentinel.database import get_credential_by_id, get_observed_scopes_for_cred, save_remediation_plan
from sentinel.harbor_system.harbor_adapter import HarborAdapter
from sentinel.finch_system.finch_adapter import FinchAdapter

class PolicyGenerator:
    """Generates down-scoped least-privilege configurations and evaluates risk reduction."""

    @staticmethod
    def generate_plan(cred_id: str) -> Optional[RemediationPlan]:
        cred = get_credential_by_id(cred_id)
        if not cred:
            return None

        system_type = SystemType(cred["system_type"])
        current_scopes = cred["granted_scopes"]
        observed_scopes = get_observed_scopes_for_cred(cred_id)

        # Recommended scopes = observed scopes (if empty, retain minimal baseline read scope)
        if observed_scopes:
            recommended_scopes = sorted(list(set(observed_scopes)))
        else:
            # Safe default fallback
            recommended_scopes = ["repository:pull"] if system_type == SystemType.HARBOR else ["directory:read"]

        revoked_scopes = sorted(list(set(current_scopes) - set(recommended_scopes)))

        # Risk before vs after
        score_before = min(100.0, sum(SCOPE_RISK_WEIGHTS.get(s, 10.0) for s in current_scopes))
        score_after = min(100.0, sum(SCOPE_RISK_WEIGHTS.get(s, 10.0) for s in recommended_scopes))
        
        reduction_percentage = 0.0
        if score_before > 0:
            reduction_percentage = max(0.0, ((score_before - score_after) / score_before) * 100.0)

        # Generate System-specific configs
        harbor_policy = None
        finch_policy = None

        if system_type == SystemType.HARBOR:
            adapter = HarborAdapter()
            harbor_policy = adapter.generate_robot_account_spec(
                robot_name=f"robot${cred['client_name'].lower().replace(' ', '-')}",
                allowed_scopes=recommended_scopes,
                project_name="prod-apps"
            )
        else:
            adapter = FinchAdapter()
            finch_policy = adapter.generate_oauth_scope_spec(
                client_id=cred["client_id"],
                allowed_scopes=recommended_scopes
            )

        # Generate OPA / Rego Policy
        rego_code = PolicyGenerator._generate_rego(
            client_name=cred["client_name"],
            cred_id=cred_id,
            system_type=system_type.value,
            allowed_scopes=recommended_scopes
        )

        plan_id = f"plan_{cred_id}_{uuid.uuid4().hex[:6]}"
        plan = RemediationPlan(
            id=plan_id,
            credential_id=cred_id,
            client_name=cred["client_name"],
            system_type=system_type,
            current_scopes=current_scopes,
            recommended_scopes=recommended_scopes,
            revoked_scopes=revoked_scopes,
            risk_score_before=score_before,
            risk_score_after=score_after,
            reduction_percentage=reduction_percentage,
            policy_harbor_json=harbor_policy,
            policy_finch_json=finch_policy,
            policy_rego=rego_code,
            status="PENDING",
            applied_at=None
        )

        save_remediation_plan(plan)
        return plan

    @staticmethod
    def _generate_rego(client_name: str, cred_id: str, system_type: str, allowed_scopes: List[str]) -> str:
        scopes_rego = ", ".join(f'"{s}"' for s in allowed_scopes)
        return f"""# Open Policy Agent (OPA) Least-Privilege Gate
# Auto-generated by SentinelGate for {client_name} ({system_type})
package sentinel.api.authz

default allow = false

# Allowed operational scopes derived from runtime telemetry
allowed_scopes := [{scopes_rego}]

# Rule: Allow request only if required scope is within least-privilege boundary
allow {{
    input.credential_id == "{cred_id}"
    input.system == "{system_type}"
    scope_is_authorized(input.required_scope)
}}

scope_is_authorized(scope) {{
    allowed_scopes[_] == scope
}}
"""
