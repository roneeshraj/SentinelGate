"""
Harbor Adapter for SentinelGate.
Audits and manages robot accounts and RBAC bindings in Harbor Container Registry.
"""

from typing import Dict, Any, List, Optional
from sentinel.harbor_system.harbor_permissions import HARBOR_SCOPES, resolve_harbor_scope
from sentinel.harbor_system.mock_harbor import MockHarborEngine

class HarborAdapter:
    """Interacts with Harbor registry (mock or remote API) to query and update robot account scopes."""

    def __init__(self, endpoint_url: str = "http://localhost:8888/mock/harbor"):
        self.endpoint_url = endpoint_url

    def test_request(self, method: str, path: str, token_scopes: List[str]) -> Dict[str, Any]:
        """Tests an API call directly against the Harbor engine."""
        status_code, body, matched_scope = MockHarborEngine.handle_request(method, path, token_scopes)
        return {
            "status_code": status_code,
            "body": body,
            "matched_scope": matched_scope,
            "allowed": status_code < 400
        }

    def generate_robot_account_spec(self, robot_name: str, allowed_scopes: List[str], project_name: str = "prod-apps") -> Dict[str, Any]:
        """
        Generates a strictly down-scoped CNCF Harbor Robot Account definition.
        Converts generic scopes to Harbor v2.0 access permissions structure.
        """
        access_permissions = []
        for scope in allowed_scopes:
            if scope == "repository:pull":
                access_permissions.append({"resource": "repository", "action": "pull"})
            elif scope == "repository:push":
                access_permissions.append({"resource": "repository", "action": "push"})
            elif scope == "repository:delete":
                access_permissions.append({"resource": "repository", "action": "delete"})
            elif scope == "artifact:read":
                access_permissions.append({"resource": "artifact", "action": "read"})
            elif scope == "artifact:delete":
                access_permissions.append({"resource": "artifact", "action": "delete"})
            elif scope == "webhook:manage":
                access_permissions.append({"resource": "notification-policy", "action": "create"})
            elif scope == "scanner:configure":
                access_permissions.append({"resource": "scan", "action": "stop"})
            elif scope == "project:admin":
                access_permissions.append({"resource": "project", "action": "manage"})

        spec = {
            "name": robot_name,
            "description": "Least-Privilege Scoped Robot Account generated by SentinelGate",
            "duration": 90, # 90 days validity
            "level": "project",
            "permissions": [
                {
                    "kind": "project",
                    "namespace": project_name,
                    "access": access_permissions
                }
            ]
        }
        return spec
